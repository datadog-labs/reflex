// Reuse the actual DRUIDS webfonts, including all Roboto Mono language subsets.
const fs = require('node:fs');
const path = require('node:path');
const source = fs.readFileSync(require.resolve('@datadog/druids/styles.css'), 'utf8');
const fonts = [...source.matchAll(/@font-face\s*\{[^}]+\}/g)].map(([face]) => {
  // Modern browsers support WOFF2; omit the duplicate WOFF/TTF payloads.
  face = face.replace(/src:(url\([^)]*\)\s*format\("woff2"\))(?:,url\([^)]*\)\s*format\("[^" ]+"\))*/g, 'src:$1');
  return face.includes('font-display:') ? face : face.replace('}', ';font-display:swap}');
});
const tokens = fs.readFileSync(path.resolve(__dirname, '../src/typography.css'), 'utf8');
fs.writeFileSync(path.resolve(__dirname, '../../src/typography.css'), '/* Generated by ui/scripts/build-typography.cjs. DRUIDS fonts and typography tokens. */\n' + fonts.join('\n') + '\n' + tokens);
console.log('Built shared DRUIDS typography and embedded WOFF2 fonts.');
